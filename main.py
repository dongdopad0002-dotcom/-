# Playwright - async browser bridge
# ============================================================
# Streamlit itself may already have an asyncio loop running.
# Therefore the Playwright Async API is hosted on its own dedicated
# background event-loop thread. LangChain sees normal synchronous
# proxy tools, while the actual browser remains fully async and is
# always accessed on the same Playwright event loop.

class _AsyncPlaywrightBridge:
    def __init__(self):
        self.loop = None
        self.thread = None
        self.ready = threading.Event()
        self.init_error = None
        self.browser = None
        self.playwright = None
        self.tools = {}

        self.thread = threading.Thread(
            target=self._thread_main,
            name="playwright-async-loop",
            daemon=True,
        )
        self.thread.start()

        if not self.ready.wait(timeout=60):
            raise RuntimeError(
                "Playwright async 초기화 시간 초과"
            )

        if self.init_error is not None:
            raise self.init_error

    def _thread_main(self):
        try:
            self.loop = asyncio.new_event_loop()
            asyncio.set_event_loop(self.loop)
            self.loop.run_until_complete(
                self._initialize_async()
            )
            self.ready.set()
            self.loop.run_forever()
        except BaseException as exc:
            self.init_error = exc
            self.ready.set()

    async def _initialize_async(self):
        # Do NOT use LangChain's create_async_playwright_browser() helper here.
        # In some versions it tries to manage the current event loop itself,
        # which conflicts with the dedicated loop used by this bridge.
        # Start Playwright directly on this loop instead.
        from playwright.async_api import async_playwright

        self.playwright = await async_playwright().start()
        self.browser = await self.playwright.chromium.launch(
            headless=True
        )

        toolkit = PWBT.from_browser(
            async_browser=self.browser
        )

        self.tools = {
            t.name: t
            for t in toolkit.get_tools()
        }

        print(
            "[PLAYWRIGHT] Async browser ready:",
            list(self.tools.keys()),
        )

    async def _invoke_async(self, tool_name, kwargs):
        playwright_tool = self.tools[tool_name]
        return await playwright_tool.ainvoke(kwargs)

    def invoke(self, tool_name, kwargs):
        if self.loop is None or not self.loop.is_running():
            raise RuntimeError(
                "Playwright async event loop is not running."
            )

        future = asyncio.run_coroutine_threadsafe(
            self._invoke_async(
                tool_name,
                kwargs,
            ),
            self.loop,
        )

        return future.result(timeout=300)


def _make_playwright_proxy(
    bridge,
    original_tool,
):
    def _proxy(**kwargs):
        return bridge.invoke(
            original_tool.name,
            kwargs,
        )

    return StructuredTool.from_function(
        func=_proxy,
        name=original_tool.name,
        description=original_tool.description,
        args_schema=original_tool.args_schema,
        infer_schema=False,
    )


