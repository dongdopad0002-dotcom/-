def _run_embedded_agent_with_ui(agent, messages):
    """Plan/Role 실행 내부의 ReAct agent도 직접 stream으로 관찰합니다."""
    final_answer = ""
    streamed_answer = False
    seen_ids = set()

    if ACTIVE_AGENT_UI is None:
        result = agent.invoke({"messages": messages})
        _record_agent_messages(result.get("messages", []))
        return result["messages"][-1].content

    try:
        for item in agent.stream(
            {"messages": messages},
            stream_mode=["messages", "updates"],
            config={"recursion_limit": 10000},
        ):
            mode = None
            payload = item
            if isinstance(item, tuple) and len(item) == 2 and item[0] in {"messages", "updates"}:
                mode, payload = item

            if mode == "messages":
                chunk = payload[0] if isinstance(payload, tuple) and len(payload) == 2 else payload
                if chunk is None:
                    continue

                # messages 스트림에는 AIMessageChunk뿐 아니라 ToolMessageChunk도
                # 들어올 수 있습니다. ToolMessage의 content를 최종 답변 스트림에
                # 절대로 합치지 않습니다. 도구 결과는 아래 ToolMessage 처리부에서
                # UI의 도구 결과 카드로만 표시합니다.
                if isinstance(chunk, TM) or str(getattr(chunk, "type", "")).lower() in {"tool", "toolmessage", "tool_message"}:
                    continue

                reasoning = AgentUI.extract_reasoning_delta(chunk)
                if reasoning:
                    ACTIVE_AGENT_UI.thinking_delta(reasoning)

                text = AgentUI.extract_text_delta(chunk)
                if text:
                    final_answer += text
                    streamed_answer = True
                    ACTIVE_AGENT_UI.answer_delta(text)
                continue

            updates = payload if isinstance(payload, dict) else None
            if not isinstance(updates, dict):
                continue

            for _, node_data in updates.items():
                if not isinstance(node_data, dict):
                    continue
                messages_out = node_data.get("messages", [])
                if not messages_out:
                    continue
                if not isinstance(messages_out, list):
                    messages_out = [messages_out]

                for message in messages_out:
                    mid = _message_identity(message)
                    if mid and mid in seen_ids:
                        continue
                    if mid:
                        seen_ids.add(mid)

                    if isinstance(message, AM):
                        _record_agent_messages([message])
                        reasoning = AgentUI.extract_reasoning_delta(message)
                        if reasoning:
                            ACTIVE_AGENT_UI.thinking_delta(reasoning, replace=True)

                        for call in getattr(message, "tool_calls", []) or []:
                            ACTIVE_AGENT_UI.tool_call(
                                call.get("name", "unknown_tool"),
                                call.get("args", {}),
                                call_id=call.get("id") or call.get("tool_call_id"),
                            )

                        if not getattr(message, "tool_calls", None) and not streamed_answer:
                            content = _content_to_text(message.content)
                            if content:
                                final_answer = content
                                ACTIVE_AGENT_UI.answer_delta(content, replace=True)

                    elif isinstance(message, TM):
                        _record_agent_messages([message])
                        ACTIVE_AGENT_UI.tool_result(
                            getattr(message, "name", None) or "tool",
                            message.content,
                            call_id=getattr(message, "tool_call_id", None),
                        )

    except Exception:
        raise

    return final_answer or ""

