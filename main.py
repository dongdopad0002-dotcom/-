def _build_react_graph(toolset: list[Any]):
    bound_llm = llm.bind_tools(toolset)

    def model_node(state: ReactGraphState):
        messages = list(state["messages"])
        injected = _subagent_completed_for_run(_ACTIVE_SUBAGENT_RUN_ID, mark_delivered=True)
        if injected:
            result_text = []
            for job in injected:
                result_text.append(
                    f"[서브에이전트 완료: {job.get('task_name','이름 없음')}]\n{job.get('result','')}"
                )
            messages.append(
                SM(content=(
                    "아래 서브에이전트 작업이 완료되었습니다. 결과를 검토하고 필요하면 현재 작업에 반영하세요.\n\n"
                    + "\n\n".join(result_text)
                ))
            )

        has_system = any(isinstance(message, SM) for message in messages)
        if not has_system:
            messages = [SM(content=REACT_SYSTEM_PROMPT), *messages]

        response = bound_llm.invoke(messages)
        return {"messages": [response]}

    def route_after_model(state: ReactGraphState):
        messages = state.get("messages", [])
        if not messages:
            return END
        last = messages[-1]
        if getattr(last, "tool_calls", None) or []:
            return "tools"
        # 서브에이전트가 남아 있는데 부모가 먼저 끝내려는 경우, 완료될 때까지 기다린 뒤
        # 결과를 다음 모델 라운드에 주입합니다.
        if _subagent_has_pending(_ACTIVE_SUBAGENT_RUN_ID):
            return "wait_subagents"
        return END

    def wait_subagents_node(state: ReactGraphState):
        deadline = time.time() + 300
        while _subagent_has_pending(_ACTIVE_SUBAGENT_RUN_ID) and time.time() < deadline:
            time.sleep(0.25)
        return {}

    graph = StateGraph(ReactGraphState)
    graph.add_node("agent", model_node)
    graph.add_node("tools", ToolNode(toolset))
    graph.add_node("wait_subagents", wait_subagents_node)
    graph.add_edge(START, "agent")
    graph.add_conditional_edges(
        "agent",
        route_after_model,
        {"tools": "tools", "wait_subagents": "wait_subagents", END: END},
    )
    graph.add_edge("tools", "agent")
    graph.add_edge("wait_subagents", "agent")
    return graph.compile()


