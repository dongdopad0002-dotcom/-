def _display_history_content(content):
    if isinstance(content, str):
        st.markdown(content)
        return

    if not isinstance(content, list):
        st.markdown(str(content))
        return

    text_parts = []
    for block in content:
        if isinstance(block, dict):
            block_type = str(block.get("type", "")).lower()
            if block_type in {"text", "input_text", "output_text"}:
                value = block.get("text", "")
                if value:
                    text_parts.append(str(value))

            elif block_type == "image_url":
                image_data = block.get("image_url", {})
                if isinstance(image_data, dict):
                    url = image_data.get("url")
                    if isinstance(url, str) and url.startswith("data:"):
                        try:
                            _, encoded = url.split(",", 1)
                            st.image(
                                base64.b64decode(encoded),
                                use_container_width=True,
                            )
                        except Exception:
                            pass

            elif block_type in {"audio_url", "video_url"}:
                # 대화 기록에는 실제 data URL도 남아 있으므로,
                # 새로고침 후에도 해당 첨부파일이 표시됩니다.
                media_data = block.get(block_type, {})
                if isinstance(media_data, dict):
                    url = media_data.get("url")
                    if isinstance(url, str) and url.startswith("data:"):
                        try:
                            _, encoded = url.split(",", 1)
                            raw = base64.b64decode(encoded)
                            if block_type == "audio_url":
                                st.audio(raw)
                            else:
                                st.video(raw)
                        except Exception:
                            pass

        elif isinstance(block, str):
            text_parts.append(block)

    if text_parts:
        st.markdown("\n".join(text_parts))


def _strip_model_control_text(text: str) -> str:
    """Gemma/OpenAI 호환 서버의 제어 토큰과 앱 UI 조각을 제거합니다."""
    text = str(text or "")

    # 앱의 제목/THINK 버튼/로컬 SVG가 모델 답변에 섞여 들어온 경우 제거합니다.
    text = re.sub(r"^\s*안녕하세요\s*\*\*소윤\*\*\s*입니다!?\s*", "", text)
    text = re.sub(r"!\[svg\]\(http://localhost:\d+/#[^)]*\)\s*", "", text, flags=re.I)
    text = re.sub(r"\[\*\*?think\*\*?\]\([^)]*image\.png[^)]*\)\s*", "", text, flags=re.I)
    text = re.sub(r"\bTHINK\b\s*사용\s*svg\s*", "", text, flags=re.I)
    text = re.sub(r"^\s*사용\s*$", "", text, flags=re.I | re.M)

    # thought 채널이 final 채널과 함께 반환되는 경우:
    # thought 내용은 버리고 final 이후만 남깁니다.
    final_marker = re.search(r"<\|channel\|>\s*final\b", text, re.IGNORECASE)
    if final_marker:
        text = text[final_marker.end():]
    else:
        # final 표식이 없고 thought 채널만 있는 경우 thought 전체를 제거합니다.
        thought_marker = re.search(r"<\|channel\|>\s*(?:thought|analysis|reasoning)\b", text, re.IGNORECASE)
        if thought_marker:
            text = text[:thought_marker.start()]

    # 남아 있는 일반 제어 토큰 제거
    text = re.sub(r"<\|(?:channel|message|end|start|eot|eom)\|>[^\n]*", "", text, flags=re.IGNORECASE)
    text = re.sub(r"<think(?:ing)?>(.*?)</think(?:ing)?\s*>", "", text, flags=re.IGNORECASE | re.DOTALL)
    text = re.sub(r"</think(?:ing)?\s*>", "", text, flags=re.IGNORECASE)

    return text.strip()


def _content_to_text(content) -> str:
    if isinstance(content, str):
        return _strip_model_control_text(content)

    if isinstance(content, list):
        parts = []
        for item in content:
            if isinstance(item, dict):
                item_type = str(item.get("type", "")).lower()
                if item_type in {
                    "text",
                    "output_text",
                }:
                    parts.append(str(item.get("text", "")))
            elif isinstance(item, str):
                parts.append(item)
        return _strip_model_control_text("\n".join(
            part for part in parts if part
        ))

    return _strip_model_control_text(str(content)) if content is not None else ""


