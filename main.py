# 실제 설치된 런타임만 실행합니다. 런타임이 없으면 거짓 성공을 만들지 않고
# "설치되지 않음"을 반환합니다. 각 호출은 독립적인 실제 프로세스에서 실행됩니다.
_LANGUAGE_EXEC_TIMEOUT = 120


def _run_external_language(
    language: str,
    code: str,
    command_variants: list[list[str]],
    suffix: str,
    compile_then_run: Optional[tuple[list[str], list[str]]] = None,
) -> str:
    code = str(code or "")
    if not code.strip():
        return f"{language}: 실행할 코드가 없습니다."

    selected = None
    for command in command_variants:
        if command and shutil.which(command[0]):
            selected = command
            break

    if selected is None:
        names = ", ".join(cmd[0] for cmd in command_variants if cmd)
        return f"{language} 런타임이 설치되어 있지 않습니다. 확인한 실행 파일: {names}"

    try:
        with tempfile.TemporaryDirectory(prefix=f"lang_{language.lower()}_") as tmp:
            path = Path(tmp) / f"main{suffix}"
            path.write_text(code, encoding="utf-8")

            if compile_then_run is not None:
                compile_cmd, run_cmd = compile_then_run
                compile_cmd = [str(x).replace("{file}", str(path)).replace("{dir}", str(tmp)) for x in compile_cmd]
                run_cmd = [str(x).replace("{file}", str(path)).replace("{dir}", str(tmp)) for x in run_cmd]
                cp = _subprocess.run(
                    compile_cmd,
                    capture_output=True,
                    stdin=_subprocess.DEVNULL,
                    timeout=_LANGUAGE_EXEC_TIMEOUT,
                )
                if cp.returncode != 0:
                    return _decode_language_output(cp.stdout, cp.stderr, cp.returncode)
                selected_run = run_cmd
            else:
                selected_run = [str(x).replace("{file}", str(path)).replace("{dir}", str(tmp)) for x in selected]

            cp = _subprocess.run(
                selected_run,
                capture_output=True,
                stdin=_subprocess.DEVNULL,
                timeout=_LANGUAGE_EXEC_TIMEOUT,
            )
            return _decode_language_output(cp.stdout, cp.stderr, cp.returncode)
    except _subprocess.TimeoutExpired:
        return f"{language} 실행 시간 초과 ({_LANGUAGE_EXEC_TIMEOUT}초)."
    except Exception as exc:
        return f"{language} 실행 오류: {exc}"


def _decode_language_output(stdout, stderr, code):
    def dec(value):
        if not value:
            return ""
        if isinstance(value, str):
            return value
        for enc in ("utf-8", "cp949", "euc-kr"):
            try:
                return value.decode(enc)
            except Exception:
                pass
        return value.decode("utf-8", errors="replace")

    out = dec(stdout).rstrip()
    err = dec(stderr).rstrip()
    if code == 0:
        return out or err or "(출력 없음)"
    text = out
    if err:
        text += ("\n" if text else "") + err
    text += f"\n[exit code: {code}]"
    return text.strip()


