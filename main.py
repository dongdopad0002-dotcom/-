def _find_todo_index(identifier: str):
    todos = _get_todos()
    value = str(identifier).strip()
    if not value:
        return None

    if value.isdigit():
        index = int(value) - 1
        if 0 <= index < len(todos):
            return index

    normalized = value.casefold()
    for index, item in enumerate(todos):
        if item["task"].casefold() == normalized:
            return index

    for index, item in enumerate(todos):
        if normalized in item["task"].casefold():
            return index

    return None


