    def tool_result(self, tool_name, result, call_id=None):
        if str(tool_name) == "subagent":
            try:
                payload = result
                if isinstance(result, str):
                    payload = json.loads(result)

                if not isinstance(payload, dict):
                    payload = {}

                group_id = payload.get("group_id")
                jobs = payload.get("jobs", [])
                if not isinstance(jobs, list):
                    jobs = []

                # 1) call_id -> 2) group_id -> 3) 아직 group_id가 없는
                #    최근 subagent 카드 순으로 찾습니다.
                card = self._find_subagent_card(
                    group_id=group_id,
                    call_id=call_id,
                )

                if card is None:
                    for candidate in reversed(self._tool_cards):
                        if candidate.get("name") != "subagent":
                            continue
                        if candidate.get("finished"):
                            continue
                        card = candidate
                        break

                if card is None:
                    card = self.subagent_group(
                        group_id,
                        jobs,
                        call_id=call_id,
                    )
                else:
                    if group_id:
                        card["group_id"] = group_id
                    if jobs:
                        # ToolMessage의 실제 job_id/status/result를
                        # 그대로 사용합니다.
                        card["jobs"] = jobs
                    if call_id and not card.get("call_id"):
                        card["call_id"] = call_id

                self.update_subagent_group(card)
                completed_jobs = [
                    job for job in jobs
                    if isinstance(job, dict)
                    and job.get("status") in {"completed", "failed"}
                ]
                for job in completed_jobs[-8:]:
                    status_label = "완료" if job.get("status") == "completed" else "실패"
                    self.thinking_delta({
                        "event": f"서브에이전트 작업 {status_label}: {job.get('task_name', '작업')}"
                    })
            except Exception as exc:
                # UI 갱신 실패 때문에 에이전트 실행 전체가 중단되지 않도록 합니다.
                print("[SUBAGENT UI] update failed:", repr(exc))
            return

        card = None

        if call_id:
            for candidate in reversed(self._tool_cards):
                if candidate.get("call_id") == call_id:
                    card = candidate
                    break

        if card is None:
            for candidate in reversed(self._tool_cards):
                if (
                    candidate.get("name") == str(tool_name)
                    and not candidate.get("finished", False)
                ):
                    card = candidate
                    break

        if card is None:
            card = self.tool_call(
                tool_name,
                {},
                call_id=call_id,
            )

        card["finished"] = True

        result_text = self.safe_text(result)
        if not result_text.strip():
            result_text = "(도구가 별도의 출력값을 반환하지 않았습니다.)"

        self.thinking_delta({"event": f"도구 결과 확인: {str(tool_name)}"})

        card["status_box"].success("완료 · 결과 확인됨")
        card["result_box"].markdown(
            '<div class="agent-tool-card" style="margin-top:8px"><b>RESULT</b><pre style="margin:9px 0 0;white-space:pre-wrap;font-size:11px">' + html.escape(result_text) + '</pre></div>',
            unsafe_allow_html=True,
        )

        # 할 일 도구가 실행된 뒤에는 목록을 즉시 갱신합니다.
        if str(tool_name) in {
            "create_todo",
            "delete_todo",
            "complete_todo",
            "complete_all_todos",
        }:
            self.render_todos()
            _persist_current_chat()

    def subagent_group(self, group_id, jobs, call_id=None):
        """서브에이전트 전체 실행 과정을 접고 펼칠 수 있는 아코디언 카드로 표시합니다."""
