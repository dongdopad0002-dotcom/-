def _json_safe(value):
    """JSON으로 저장할 수 없는 값이 있어도 대화 저장이 실패하지 않도록 변환합니다."""
    if value is None or isinstance(value, (str, int, float, bool)):
        return value
    if isinstance(value, dict):
        return {str(k): _json_safe(v) for k, v in value.items()}
    if isinstance(value, (list, tuple)):
        return [_json_safe(v) for v in value]
    try:
        json.dumps(value)
        return value
    except Exception:
        return str(value)


def _serialize_message(message):
    data = {
        "id": getattr(message, "id", None),
        "content": _json_safe(getattr(message, "content", "")),
    }

    if isinstance(message, SM):
        data["type"] = "system"
    elif isinstance(message, HM):
        data["type"] = "human"
    elif isinstance(message, AM):
        data["type"] = "ai"
        data["tool_calls"] = _json_safe(getattr(message, "tool_calls", []) or [])
        data["invalid_tool_calls"] = _json_safe(
            getattr(message, "invalid_tool_calls", []) or []
        )
        data["additional_kwargs"] = _json_safe(
            getattr(message, "additional_kwargs", {}) or {}
        )
        data["response_metadata"] = _json_safe(
            getattr(message, "response_metadata", {}) or {}
        )
    elif isinstance(message, TM):
        data["type"] = "tool"
        data["tool_call_id"] = getattr(message, "tool_call_id", "")
        data["name"] = getattr(message, "name", None)
        data["status"] = getattr(message, "status", None)
    else:
        return None

    return data


def _deserialize_message(data):
    if not isinstance(data, dict):
        return None

    message_type = data.get("type")
    content = data.get("content", "")
    message_id = data.get("id")

    try:
        if message_type == "system":
            return SM(content=content, id=message_id)

        if message_type == "human":
            return HM(content=content, id=message_id)

        if message_type == "ai":
            kwargs = {
                "content": content,
                "id": message_id,
                "tool_calls": data.get("tool_calls", []) or [],
                "invalid_tool_calls": data.get("invalid_tool_calls", []) or [],
                "additional_kwargs": data.get("additional_kwargs", {}) or {},
                "response_metadata": data.get("response_metadata", {}) or {},
            }
            return AM(**kwargs)

        if message_type == "tool":
            kwargs = {
                "content": content,
                "tool_call_id": data.get("tool_call_id", ""),
                "name": data.get("name"),
                "id": message_id,
            }
            if data.get("status"):
                kwargs["status"] = data["status"]
            return TM(**kwargs)

    except Exception:
        # 구버전 LangChain에서 일부 필드가 지원되지 않는 경우에도
        # 핵심 대화 내용은 복구합니다.
        try:
            if message_type == "system":
                return SM(content=content)
            if message_type == "human":
                return HM(content=content)
            if message_type == "ai":
                return AM(
                    content=content,
                    tool_calls=data.get("tool_calls", []) or [],
                )
            if message_type == "tool":
                return TM(
                    content=content,
                    tool_call_id=data.get("tool_call_id", ""),
                )
        except Exception:
            return None

    return None


def _message_text_for_title(message):
    if not isinstance(message, HM):
        return ""

    content = getattr(message, "content", "")

    if isinstance(content, str):
        return content.strip()

    if isinstance(content, list):
        parts = []
        for block in content:
            if isinstance(block, dict):
                block_type = str(block.get("type", "")).lower()
                if block_type in {"text", "input_text"}:
                    text = block.get("text", "")
                    if text:
                        parts.append(str(text))
            elif isinstance(block, str):
                parts.append(block)
        return " ".join(parts).strip()

    return str(content).strip()


def _make_chat_title(messages):
    for message in messages:
        text = _message_text_for_title(message)
        if text:
            text = " ".join(text.split())
            if len(text) > 32:
                return text[:32] + "…"
            return text
    return "새 채팅"


