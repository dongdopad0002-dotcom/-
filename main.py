def _record_agent_messages(messages: list[Any]) -> None:
    """에이전트가 생성한 AIMessage/ToolMessage를 세션 대화 기록에 한 번만 추가합니다."""
    if "chat_history" not in st.session_state:
        st.session_state["chat_history"] = [SM(content=user_instructions)]
    history = st.session_state["chat_history"]
    existing_ids = {
        getattr(item, "id", None)
        for item in history
        if getattr(item, "id", None)
    }
    for message in messages or []:
        if not isinstance(message, (AM, TM)):
            continue
        message_id = getattr(message, "id", None)
        if message_id and message_id in existing_ids:
            continue
        history.append(message)
        if message_id:
            existing_ids.add(message_id)


