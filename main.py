# ==========================================================
def _run_planning_mode(mode_name: str, user_input):
    if not user_input:
        return

    if not (user_input.text or user_input.files):
        return

    query, user_message, _ = _prepare_planning_query(user_input)

    with st.chat_message("user"):
        _display_history_content(user_message.content)
    _append_history_message(user_message)

    with st.chat_message("assistant"):
        ui = AgentUI(st.container())
        _set_active_agent_ui(ui)
        final_output = ""

        try:
            if mode_name == "SinglePathPlanGeneration":
                runner = SinglePathPlanGeneration(llm=llm)
                initial_state = SinglePathPlanGenerationState(query=query)
                recursion_limit = 5000
                final_key = "final_output"
                graph = runner.graph

            elif mode_name == "MultiPathPlanGeneration":
                runner = MultiPathPlanGeneration(llm=llm)
                initial_state = MultiPathPlanGenerationState(query=query)
                recursion_limit = 5000
                final_key = "final_output"
                graph = runner.graph

            elif mode_name == "RoleBasedCoorperation":
                runner = RoleBasedCooperation(llm=llm)
                initial_state = AgentState(query=query)
                recursion_limit = 1000
                final_key = "final_report"
                graph = runner.graph

            else:
                raise ValueError("지원하지 않는 실행 방식입니다.")

            _plan_status(f"🚀 {mode_name} 시작")

            for update in graph.stream(
                initial_state,
                {"recursion_limit": recursion_limit},
                stream_mode="updates",
            ):
                if not isinstance(update, dict):
                    continue

                for node_name, node_update in update.items():
                    nice_name = {
                        "goal_setting": "목표 설정",
                        "decompose_query": "태스크 분해",
                        "present_options": "옵션 선택",
                        "execute_task": "태스크 실행",
                        "aggregate_results": "결과 종합",
                        "planner": "계획 수립",
                        "role_assigner": "역할 배정",
                        "executor": "실행",
                        "reporter": "보고서 작성",
                    }.get(node_name, node_name)

                    _plan_status(f"✅ {nice_name} 단계 완료")

                    if isinstance(node_update, dict) and final_key in node_update:
                        final_output = str(node_update[final_key])

            ui.render_todos()
            _render_main_todo_panel()

            if final_output:
                ui.answer_delta(final_output, replace=True)
                _append_history_message(AM(content=final_output))
            else:
                ui.answer_delta("실행은 완료되었지만 최종 결과가 없습니다.", replace=True)

        except Exception as exc:
            error_text = f"실행 중 오류가 발생했습니다: {exc}"
            st.error(error_text)
            _append_history_message(AM(content=error_text))

        finally:
            _set_active_agent_ui(None)
            _persist_current_chat()


