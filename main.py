def _subagent_run_snapshot(run_id: Optional[str]):
    with _SUBAGENT_LOCK:
        run = _SUBAGENT_RUNS.get(run_id or "")
        if not run:
            return None
        return json.loads(json.dumps(run, ensure_ascii=False, default=str))


def _subagent_has_pending(run_id: Optional[str]) -> bool:
    snap = _subagent_run_snapshot(run_id)
    if not snap:
        return False
    return any(job.get("status") in {"queued", "running"} for job in snap.get("jobs", {}).values())


def _subagent_completed_for_run(run_id: Optional[str], mark_delivered: bool = True):
    with _SUBAGENT_LOCK:
        run = _SUBAGENT_RUNS.get(run_id or "")
        if not run:
            return []
        completed = []
        for job_id, job in run.get("jobs", {}).items():
            if job.get("status") not in {"completed", "failed"}:
                continue
            if mark_delivered and job.get("delivered"):
                continue
            completed.append(dict(job))
            if mark_delivered:
                job["delivered"] = True
        return completed


def _execute_one_subagent(run_id: str, job_id: str, task_name: str, prompt: str):
    with _SUBAGENT_LOCK:
        run = _SUBAGENT_RUNS.get(run_id)
        if not run:
            return
        run["jobs"][job_id]["status"] = "running"
        run["jobs"][job_id]["started_at"] = datetime.now().isoformat(timespec="seconds")

    try:
        graph = _ACTIVE_SUBAGENT_NO_SUB_GRAPH
        if graph is None:
            graph = _build_react_graph(list(REACT_BASE_TOOLS))

        worker_messages = [
            SM(content=REACT_SYSTEM_PROMPT + "\n\n당신은 현재 에이전트가 생성한 서브에이전트입니다. subagent 도구는 사용할 수 없습니다."),
            HM(content=(
                f"작업 이름: {task_name}\n\n"
                f"작업 지시:\n{prompt}\n\n"
                "주어진 작업만 독립적으로 수행하고 실제 결과를 반환하세요."
            )),
        ]
        result = graph.invoke(
            {"messages": worker_messages},
            {"recursion_limit": 10000},
        )
        result_messages = result.get("messages", []) if isinstance(result, dict) else []
        final = ""
        for msg in reversed(result_messages):
            if isinstance(msg, AM) and not getattr(msg, "tool_calls", None):
                final = _content_to_text(msg.content)
                if final:
                    break
        if not final and result_messages:
            final = _content_to_text(getattr(result_messages[-1], "content", ""))
        if not final:
            final = "서브에이전트가 결과를 반환하지 않았습니다."

        with _SUBAGENT_LOCK:
            job = _SUBAGENT_RUNS.get(run_id, {}).get("jobs", {}).get(job_id)
            if job is not None:
                job["status"] = "completed"
                job["result"] = final
                job["finished_at"] = datetime.now().isoformat(timespec="seconds")
    except Exception as exc:
        with _SUBAGENT_LOCK:
            job = _SUBAGENT_RUNS.get(run_id, {}).get("jobs", {}).get(job_id)
            if job is not None:
                job["status"] = "failed"
                job["result"] = f"서브에이전트 오류: {exc}"
                job["finished_at"] = datetime.now().isoformat(timespec="seconds")


def _coerce_subagent_string_list(value: Any) -> list[str]:
    """Gemma가 리스트를 JSON 문자열로 반환하는 경우까지 안전하게 리스트로 변환합니다."""
    if isinstance(value, list):
        return [str(item) for item in value]

    if value is None:
        return []

    if not isinstance(value, str):
        return [str(value)]

    text = value.strip()
    if not text:
        return []

    # 정상 JSON/Python 리스트 문자열
    if text.startswith("[") and text.endswith("]"):
        for parser in (json.loads, ast.literal_eval):
            try:
                parsed = parser(text)
                if isinstance(parsed, list):
                    return [str(item) for item in parsed]
            except Exception:
                pass

        # Gemma가 [파일 삭제]처럼 따옴표 없는 단일 항목을 생성한 경우
        inner = text[1:-1].strip()
        if not inner:
            return []

        # 쉼표가 있는 경우에는 항목별로 분리
        pieces = [part.strip() for part in re.split(r",\s*", inner) if part.strip()]
        return [part.strip("\\\"'") for part in pieces]

    # 리스트 표기를 아예 생략하고 한 항목만 전달한 경우
    return [text.strip("\\\"'")]


@tool("subagent")
def subagent(
    ai_count: int | str,
    task_names: list[str] | str,
    prompts: list[str] | str,
) -> str:
    """고급 작업을 여러 서브에이전트에게 병렬 위임합니다.

    Gemma가 배열을 실제 JSON array 대신 문자열('[작업]')로 생성하는
    경우에도 입력을 정상적인 리스트로 복원하여 실행합니다.
    현재 에이전트는 서브에이전트 실행 중에도 자신의 작업을 계속합니다.
    각 서브에이전트는 동일한 ReAct 그래프를 사용하지만 subagent 도구는 사용할 수 없습니다.
    """
    try:
        ai_count = int(ai_count)
    except Exception:
        return "ai_count는 정수여야 합니다."

    task_names = _coerce_subagent_string_list(task_names)
    prompts = _coerce_subagent_string_list(prompts)

    if ai_count < 1:
        return "ai_count는 1 이상이어야 합니다."
    if ai_count > 16:
        return "한 번에 최대 16개의 서브에이전트까지 실행할 수 있습니다."

    # 하나의 문자열을 하나의 작업으로 정상 취급한 뒤, 실제 작업 수와 맞춥니다.
    if len(task_names) != ai_count or len(prompts) != ai_count:
        return f"ai_count({ai_count}), task_names({len(task_names)}), prompts({len(prompts)})의 길이가 모두 같아야 합니다."

    run_id = _ACTIVE_SUBAGENT_RUN_ID or ("run_" + uuid.uuid4().hex)
    group_id = "subgroup_" + uuid.uuid4().hex[:12]
    jobs = {}

    with _SUBAGENT_LOCK:
        if run_id not in _SUBAGENT_RUNS:
            _SUBAGENT_RUNS[run_id] = {"group_id": group_id, "jobs": {}}
        run = _SUBAGENT_RUNS[run_id]
        run["group_id"] = group_id
        for index in range(ai_count):
            job_id = f"{group_id}_{index + 1}"
            task_name = str(task_names[index])
            prompt = str(prompts[index])
            job = {
                "job_id": job_id,
                "group_id": group_id,
                "task_name": task_name,
                "prompt": prompt,
                "status": "queued",
                "result": "",
                "delivered": False,
            }
            run["jobs"][job_id] = job
            jobs[job_id] = job

    # 모두 한 번에 제출하므로 순차 실행이 아니라 병렬 실행입니다.
    for job_id, job in jobs.items():
        _SUBAGENT_EXECUTOR.submit(
            _execute_one_subagent,
            run_id,
            job_id,
            job["task_name"],
            job["prompt"],
        )

    return json.dumps(
        {
            "status": "started",
            "group_id": group_id,
            "message": "모든 서브에이전트 작업을 병렬로 시작했습니다. 기존 에이전트는 다른 작업을 계속할 수 있습니다.",
            "jobs": [
                {"job_id": j["job_id"], "task_name": j["task_name"], "status": j["status"]}
                for j in jobs.values()
            ],
        },
        ensure_ascii=False,
    )


