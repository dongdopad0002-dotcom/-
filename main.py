def _message_identity(message):
    message_id = getattr(message, "id", None)
    return str(message_id) if message_id else None


def _append_history_message(message):
    if not isinstance(message, (HM, AM, TM, SM)):
        return

    if "chat_history" not in st.session_state:
        st.session_state["chat_history"] = [
            SM(content=REACT_SYSTEM_PROMPT)
        ]

    history = st.session_state["chat_history"]
    message_id = _message_identity(message)

    if message_id:
        for old in history:
            if _message_identity(old) == message_id:
                return

    history.append(message)
    _persist_current_chat()


def _extract_uploaded_file_info(uploaded_files):
    saved = []
    current_dir = os.getcwd()

    for uploaded in uploaded_files or []:
        filename = os.path.basename(
            getattr(uploaded, "name", "uploaded_file")
        ) or "uploaded_file"
        filename = filename.replace("\\", "_").replace("/", "_")
        target = os.path.join(current_dir, filename)

        try:
            data = uploaded.getvalue()
            with open(target, "wb") as f:
                f.write(data)
            saved.append(target)
        except Exception as exc:
            saved.append(
                f"{filename} (저장 실패: {exc})"
            )

    try:
        _register_uploaded_retrievers(saved)
    except Exception as exc:
        # 파일 업로드 자체는 실패시키지 않고 retriever만 실패 처리합니다.
        print("[RETRIEVER] registration failed:", repr(exc))

    return saved


def _build_user_query(user_input) -> tuple[str, list[str]]:
    """첨부 파일을 현재 작업 폴더에 저장하고 일반 텍스트 질의를 생성합니다."""
    text = str(
        getattr(user_input, "text", "") or ""
    ).strip()

    files = list(
        getattr(user_input, "files", []) or []
    )

    saved_paths = _extract_uploaded_file_info(files)

    if saved_paths:
        file_text = "\n".join(
            f"- {path}" for path in saved_paths
        )

        attachment_context = (
            "\n\n[첨부 파일]\n"
            "사용자가 첨부한 파일은 현재 작업 폴더에 저장되어 있습니다. "
            "필요하면 파일 도구 또는 터미널 도구로 실제 파일을 확인하세요.\n"
            f"{file_text}"
        )

        text = (
            text + attachment_context
        ).strip()

    return text, saved_paths


def _prepare_planning_query(user_input):
    """
    계획형 모드에서도 이미지/오디오/비디오를 실제 모델 입력으로 전달합니다.
    미디어가 있으면 1차 멀티모달 이해 단계를 거쳐 기존 계획 파이프라인이
    사용할 수 있는 텍스트 목표로 변환합니다.
    """
    multimodal_message, saved_paths = _build_multimodal_user_message(
        user_input
    )

    uploaded_files = list(
        getattr(user_input, "files", []) or []
    )

    has_multimodal = False
    for uploaded in uploaded_files:
        mime_type = str(
            getattr(uploaded, "type", "") or ""
        ).lower()
        if not mime_type:
            name = str(getattr(uploaded, "name", "") or "")
            mime_type, _ = mimetypes.guess_type(name)
            mime_type = (mime_type or "").lower()

        if (
            mime_type.startswith("image/")
            or mime_type.startswith("audio/")
            or mime_type.startswith("video/")
        ):
            has_multimodal = True
            break

    text = str(
        getattr(user_input, "text", "") or ""
    ).strip()

    if not has_multimodal:
        query, _ = _build_user_query(user_input)
        return (
            query or "첨부 파일을 확인하고 요청을 처리해 주세요.",
            multimodal_message,
            saved_paths,
        )

    # 실제 이미지/오디오/비디오를 Gemma에 직접 전달합니다.
    analysis_prompt = (
        "사용자의 입력과 첨부된 이미지/오디오/비디오를 실제로 분석하세요.\n"
        "이 입력을 이후 계획형 에이전트가 실행할 수 있는 구체적인 작업 목표로 정리하세요.\n"
        "첨부된 미디어에서 확인되는 중요한 사실을 포함하세요.\n"
        "추측으로 사실을 만들지 마세요.\n"
        "최종 결과는 한국어 텍스트로 작성하세요.\n\n"
        f"사용자 요청: {text or '(텍스트 요청 없음)'}"
    )

    content = list(multimodal_message.content)
    content.insert(
        0,
        {
            "type": "text",
            "text": analysis_prompt,
        },
    )

    try:
        understanding = llm.invoke(
            HM(content=content)
        )
        analyzed = _content_to_text(
            getattr(understanding, "content", "")
        ).strip()
    except Exception as exc:
        analyzed = (
            f"멀티모달 입력 분석에 실패했습니다: {exc}"
        )

    if not analyzed:
        analyzed = text or "첨부 미디어를 분석하고 요청을 처리해 주세요."

    if saved_paths:
        file_text = "\n".join(
            f"- {path}" for path in saved_paths
        )
        analyzed += (
            "\n\n[첨부 파일 경로]\n"
            "사용자가 첨부한 원본 파일은 현재 작업 폴더에 저장되어 있습니다.\n"
            f"{file_text}"
        )

    return analyzed, multimodal_message, saved_paths


def _build_multimodal_user_message(user_input):
    text = str(
        getattr(user_input, "text", "") or ""
    ).strip()

    uploaded_files = list(
        getattr(user_input, "files", []) or []
    )

    saved_paths = _extract_uploaded_file_info(
        uploaded_files
    )

    content_blocks = []

    if text:
        content_blocks.append({
            "type": "text",
            "text": text,
        })

    unsupported = []

    for uploaded, saved_path in zip(
        uploaded_files,
        saved_paths,
    ):
        if (
            not isinstance(saved_path, str)
            or not os.path.isfile(saved_path)
        ):
            unsupported.append(str(saved_path))
            continue

        mime_type = str(
            getattr(uploaded, "type", "") or ""
        ).lower()

        if not mime_type:
            mime_type, _ = mimetypes.guess_type(
                saved_path
            )
            mime_type = (
                mime_type or ""
            ).lower()

        try:
            if mime_type.startswith("image/"):
                data_url = image_to_data_url(
                    saved_path
                )
                content_blocks.append({
                    "type": "image_url",
                    "image_url": {
                        "url": data_url
                    },
                })

            elif mime_type.startswith("audio/"):
                data_url = audio_to_data_url(saved_path)
                # Gemma 4 E4B는 오디오 입력을 지원하며, 음성 전사 요청을 명시하면
                # 단순 파일 존재 확인이 아니라 실제 음성 내용을 인식하도록 유도합니다.
                content_blocks.append({
                    "type": "text",
                    "text": (
                        "다음 오디오를 실제로 듣고 음성을 인식하세요. "
                        "사용자가 별도 지시를 하지 않았다면 먼저 음성 내용을 정확하게 전사하고, "
                        "그 다음 사용자의 요청에 답하세요. 들리지 않는 부분은 추측하지 마세요."
                    ),
                })
                content_blocks.append({
                    "type": "audio_url",
                    "audio_url": {
                        "url": data_url
                    },
                })

            elif mime_type.startswith("video/"):
                data_url = video_to_data_url(
                    saved_path
                )
                content_blocks.append({
                    "type": "video_url",
                    "video_url": {
                        "url": data_url
                    },
                })

            else:
                unsupported.append(saved_path)

        except Exception as exc:
            unsupported.append(
                f"{saved_path} (변환 실패: {exc})"
            )

    if unsupported:
        content_blocks.append({
            "type": "text",
            "text": (
                "[첨부 파일 경로]\n"
                + "\n".join(
                    f"- {path}"
                    for path in unsupported
                )
                + "\n필요하면 파일 도구 또는 터미널 도구로 실제 파일을 확인하세요."
            ),
        })

    if not content_blocks:
        content_blocks.append({
            "type": "text",
            "text": "첨부 파일을 확인하고 요청을 처리해 주세요.",
        })

    return (
        HM(content=content_blocks),
        saved_paths,
    )


