def _delete_current_chat():
    store = _ensure_chat_store()
    current_id = store["active_chat_id"]

    remaining = [
        chat for chat in store["chats"]
        if chat["id"] != current_id
    ]

    if not remaining:
        new_chat = _new_chat_record()
        remaining = [new_chat]
        new_active = new_chat["id"]
    else:
        remaining.sort(
            key=lambda c: c.get("updated_at", ""),
            reverse=True,
        )
        new_active = remaining[0]["id"]

    store["chats"] = remaining
    store["active_chat_id"] = new_active
    _save_chat_store(store)
    _load_active_chat_into_session()


