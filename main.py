def _atomic_replace(src: str, dst: str, attempts: int = 20, delay: float = 0.15):
    last_error = None
    for _ in range(attempts):
        try:
            os.replace(src, dst)
            return
        except PermissionError as exc:
            last_error = exc
            time.sleep(delay)
    if last_error is not None:
        raise last_error


def _load_chat_store():
    if not os.path.exists(CHAT_STORE_FILE):
        chat = _new_chat_record()
        store = {
            "version": 2,
            "active_chat_id": chat["id"],
            "chats": [chat],
        }
        _save_chat_store(store)
        return store

    try:
        with open(CHAT_STORE_FILE, "r", encoding="utf-8") as f:
            store = json.load(f)

        if not isinstance(store, dict):
            raise ValueError("채팅 저장 파일 형식이 올바르지 않습니다.")

        chats = store.get("chats", [])
        if isinstance(chats, dict):
            chats = list(chats.values())

        normalized = []
        for chat in chats:
            if not isinstance(chat, dict):
                continue
            if not chat.get("id"):
                chat["id"] = uuid.uuid4().hex
            chat.setdefault("title", "새 채팅")
            chat.setdefault("created_at", datetime.now().isoformat(timespec="seconds"))
            chat.setdefault("updated_at", chat["created_at"])
            chat.setdefault("messages", [])
            chat.setdefault("todos", [])
            normalized.append(chat)

        if not normalized:
            normalized.append(_new_chat_record())

        active_id = store.get("active_chat_id")
        if not any(c["id"] == active_id for c in normalized):
            active_id = normalized[0]["id"]

        result = {
            "version": 2,
            "active_chat_id": active_id,
            "chats": sorted(
                normalized,
                key=lambda c: c.get("updated_at", ""),
                reverse=True,
            ),
        }
        return result

    except Exception:
        # 손상된 저장 파일은 백업 후 새 저장소를 만듭니다.
        try:
            backup = CHAT_STORE_FILE + ".broken"
            if os.path.exists(backup):
                os.remove(backup)
            _atomic_replace(CHAT_STORE_FILE, backup)
        except Exception:
            pass

        chat = _new_chat_record()
        store = {
            "version": 2,
            "active_chat_id": chat["id"],
            "chats": [chat],
        }
        _save_chat_store(store)
        return store


def _save_chat_store(store=None):
    if store is None:
        store = st.session_state.get("chat_store")
    if not store:
        return

    temp_file = (
        CHAT_STORE_FILE
        + f".{os.getpid()}.{threading.get_ident()}.tmp"
    )

    with CHAT_STORE_LOCK:
        try:
            with open(temp_file, "w", encoding="utf-8") as f:
                json.dump(
                    _json_safe(store),
                    f,
                    ensure_ascii=False,
                    indent=2,
                )

            _atomic_replace(
                temp_file,
                CHAT_STORE_FILE,
            )
        finally:
            try:
                if os.path.exists(temp_file):
                    os.remove(temp_file)
            except Exception:
                pass


def _ensure_chat_store():
    """도구/에이전트가 먼저 실행되어도 chat_store가 항상 존재하도록 보장합니다."""
    if "chat_store" not in st.session_state:
        st.session_state["chat_store"] = _load_chat_store()
    return st.session_state["chat_store"]


def _get_active_chat_record():
    store = _ensure_chat_store()
    active_id = store["active_chat_id"]
    for chat in store["chats"]:
        if chat["id"] == active_id:
            return chat
    chat = _new_chat_record()
    store["chats"].insert(0, chat)
    store["active_chat_id"] = chat["id"]
    _save_chat_store(store)
    return chat


